export function resolveZork1RoomKey(startRoomObjectId, currentRoomObjectId) {
  if (!Number.isInteger(startRoomObjectId) || !Number.isInteger(currentRoomObjectId)) return null;
  const roomIndex = currentRoomObjectId - startRoomObjectId;
  return ZORK1_ROOM_ORDER[roomIndex] ?? null;
}
